const TEKSTY = { pl, en, de, es, fr, uk, cs, it, pt };

let jezyk = 'pl';

export function ustawJezyk(kod) {
  if (TEKSTY[kod]) {
    jezyk = kod;
    try { localStorage.setItem('slad.jezyk', kod); } catch { /* prywatny tryb */ }
  }
}

export function jezykStartowy() {
  let zapisany = null;
  try { zapisany = localStorage.getItem('slad.jezyk'); } catch { /* ignoruj */ }
  if (zapisany && TEKSTY[zapisany]) return zapisany;
  const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
  return TEKSTY[nav] ? nav : 'en';
}

export function aktualnyJezyk() {
  return jezyk;
}

/** Tłumaczenie klucza z podstawianiem {parametrów}. */
export function t(klucz, parametry) {
  let s = TEKSTY[jezyk]?.[klucz] ?? TEKSTY.en[klucz] ?? klucz;
  if (parametry) {
    for (const [k, v] of Object.entries(parametry)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}
